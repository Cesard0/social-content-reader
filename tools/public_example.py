"""Generate and collect original synthetic media; publish only allowlisted artifacts.

Run from the repository root: python3 tools/public_example.py /tmp/scr-example-run
Requires FFmpeg/ffprobe. No platform download, model call, or human score.
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from content_eval.evidence import collect


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="New local working directory")
    args = parser.parse_args()
    root = args.output.resolve()
    if root.exists():
        parser.error("Use a new directory; existing artifacts are never overwritten")
    if not all(shutil.which(tool) for tool in ("ffmpeg", "ffprobe")):
        parser.error("Install FFmpeg and ffprobe first")
    root.mkdir(parents=True)
    source = root / "source"
    source.mkdir()
    base = "color=c=0xf3efdf:s=640x360:r=10:d=6"
    boxes = ",drawbox=x=80:y=120:w=100:h=100:color=red:t=fill:enable='lt(t,3)'"
    boxes += ",drawbox=x=460:y=120:w=100:h=100:color=green:t=fill:enable='gte(t,3)'"
    for name in ("steady", "brief"):
        graph = base + boxes
        if name == "brief":
            graph += ",drawbox=x=0:y=0:w=640:h=35:color=blue:t=fill:enable='gte(t,2.8)*lt(t,3)'"
        subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-f", "lavfi", "-i", graph,
                        "-c:v", "mpeg4", "-q:v", "2", str(source / (name + ".mp4"))], check=True)
    (source / "transcript.txt").write_text(
        "[00:00-00:06] The indicator changes position halfway through.\n", encoding="utf-8")
    (source / "context.txt").write_text(
        "Original synthetic fixture. Not a real product or customer recording. "
        "The supplied transcript is authored text, not an ASR result.\n", encoding="utf-8")
    items = [{"id": name, "file": "source/" + name + ".mp4", "platform": "synthetic",
              "transcript_file": "source/transcript.txt", "post_context_file": "source/context.txt",
              "requires": ["frames", "transcript", "post_context"]} for name in ("steady", "brief")]
    items.append({"id": "missing", "file": "source/intentionally-missing.mp4", "platform": "synthetic",
                  "requires": ["frames"]})
    manifest = root / "manifest.json"
    manifest.write_text(json.dumps({"items": items}, indent=2), encoding="utf-8")
    started = time.perf_counter()
    batch = collect(manifest, root / "collection", frame_count=2)
    elapsed = round(time.perf_counter() - started, 3)
    # Verify that a second collection reuses exactly the saved bundle.
    assert collect(manifest, root / "collection", frame_count=2) == batch
    assert [r["retrieval"]["status"] for r in batch["items"]] == ["success", "success", "failed"]
    assert [r["preparation"]["status"] for r in batch["items"]] == ["success", "success", "failed"]
    exported = Path(__file__).resolve().parents[1] / "docs/examples/controlled"
    exported.mkdir(parents=True, exist_ok=True)
    for name in ("steady", "brief"):
        shutil.copyfile(source / (name + ".mp4"), exported / (name + ".mp4"))
        for index in (0, 1):
            shutil.copyfile(root / "collection" / name / ("frame-%03d.jpg" % index),
                            exported / (name + "-%d.jpg" % index))
    for name in ("transcript.txt", "context.txt"):
        shutil.copyfile(source / name, exported / name)
    subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-ss", "2.9", "-i", str(source / "brief.mp4"),
                    "-frames:v", "1", "-y", str(exported / "brief-extra-2.9.jpg")], check=True)
    result = {"kind": "executed synthetic collection check; not a comprehension benchmark",
              "source": "Original fixtures generated by tools/public_example.py",
              "review": "Codex self-review; no independent or human review",
              "collection_seconds": elapsed, "timing_scope": "Local collection only; excludes fixture generation and interpretation",
              "cache_reuse": "Verified by recollection and exact record equality",
              "items": [{"id": r["id"], "retrieval": r["retrieval"]["status"],
                         "preparation": r["preparation"]["status"], "audio": r["audio"]["status"],
                         "transcript": r["transcript"]["status"],
                         "sample_seconds": [f["seconds"] for f in r["frames"].get("frames", [])]}
                        for r in batch["items"]],
              "tools": batch["items"][0]["tool_versions"],
              "limitations": ["Designed cases, not representative social posts", "No platform access tested",
                              "Supplied text, not speech recognition", "No model accuracy or user benefit measured",
                              "Two sampled frames miss the brief blue banner", "No production reliability claim"]}
    result["sha256"] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                        for p in sorted(exported.iterdir()) if p.suffix in (".mp4", ".jpg", ".txt")}
    (exported / "collection.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
